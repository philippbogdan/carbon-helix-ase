"""Logical Clifford gates of the Helix codes: symplectic actions of physical circuits,
the automorphism and phase-gate generators of arXiv:2609.03194 (Fig. 4, Fig. 5c,
Fig. 10), and the Cayley-graph lookup compiler over Sp(4,2).

Paulis on n qubits are symplectic vectors v = (x | z) in GF(2)^{2n}.
Ops: ('H', q), ('S', q), ('SDG', q), ('CX', c, t), ('CZ', a, b), ('SWAP', a, b),
     ('PERM', perm) with perm[i] = new position of qubit i.
"""
from __future__ import annotations

import heapq
import itertools

import numpy as np

from .gf2 import solve, rank


def conj_pauli(v: np.ndarray, ops, n: int) -> np.ndarray:
    """U P U^dagger for U = ops applied in order (first op first). Signs ignored."""
    x = v[:n].copy()
    z = v[n:].copy()
    for op in ops:
        name = op[0]
        if name == "H":
            q = op[1]
            x[q], z[q] = z[q], x[q]
        elif name in ("S", "SDG"):
            q = op[1]
            z[q] ^= x[q]
        elif name == "CX":
            c, t = op[1], op[2]
            x[t] ^= x[c]
            z[c] ^= z[t]
        elif name == "CZ":
            a, b = op[1], op[2]
            z[a] ^= x[b]
            z[b] ^= x[a]
        elif name == "SWAP":
            a, b = op[1], op[2]
            x[a], x[b] = x[b], x[a]
            z[a], z[b] = z[b], z[a]
        elif name == "PERM":
            perm = op[1]
            nx = np.zeros_like(x)
            nz = np.zeros_like(z)
            for i, j in enumerate(perm):
                nx[j] = x[i]
                nz[j] = z[i]
            x, z = nx, nz
        else:
            raise ValueError(name)
    return np.concatenate([x, z])


def code_paulis(code):
    """Symplectic vectors of stabilizer generators and logical operators (order:
    X0, X1, Z0, Z1)."""
    n = code.n
    stabs = []
    for r in code.hx:
        stabs.append(np.concatenate([r, np.zeros(n, dtype=np.uint8)]))
    for r in code.hz:
        stabs.append(np.concatenate([np.zeros(n, dtype=np.uint8), r]))
    logs = []
    for r in code.lx:
        logs.append(np.concatenate([r, np.zeros(n, dtype=np.uint8)]))
    for r in code.lz:
        logs.append(np.concatenate([np.zeros(n, dtype=np.uint8), r]))
    return np.array(stabs, dtype=np.uint8), np.array(logs, dtype=np.uint8)


def decompose(v, stabs, logs):
    """Write v = sum a_i logs_i + sum b_j stabs_j. Returns (a, b) or None."""
    A = np.vstack([logs, stabs])
    x = solve(A, v)
    if x is None:
        return None
    return x[:len(logs)], x[len(logs):]


def logical_action(code, ops):
    """4x4 GF(2) matrix M with U L_i U^dag = sum_j M[i, j] L_j (mod stabilizers), for
    logical basis (X0, X1, Z0, Z1); raises if U does not preserve the code."""
    stabs, logs = code_paulis(code)
    n = code.n
    for s in stabs:
        img = conj_pauli(s, ops, n)
        d = decompose(img, stabs, logs)
        if d is None or d[0].any():
            raise ValueError("circuit does not preserve the stabilizer group")
    M = np.zeros((len(logs), len(logs)), dtype=np.uint8)
    for i, L in enumerate(logs):
        img = conj_pauli(L, ops, n)
        d = decompose(img, stabs, logs)
        if d is None:
            raise ValueError("logical not mapped into the normalizer")
        M[i] = d[0]
    return M


# ------------------------------------------------------------------ C4-Helix generators
def swap_ops(pairs):
    return [("SWAP", a, b) for a, b in pairs]


def c4helix_generators():
    """Automorphisms of the [[20,2,6]] code, column 5 of Fig. 4 of arXiv:2609.03194,
    and the S0S1 phase gate of Fig. 5(c) (CZs and S gates, without flag gadgets)."""
    g = {}
    g["aut_H"] = swap_ops([(4 * i, 2 + 4 * i) for i in range(5)] +
                          [(i, i + 4) for i in range(4)] +
                          [(i + 12, i + 16) for i in range(4)] +
                          [(i + 4, i + 12) for i in range(4)])
    g["aut_HS"] = swap_ops([(4 * i, 2 + 4 * i) for i in range(5)] +
                           [(4 * i, 3 + 4 * i) for i in range(5)])
    g["aut_HH"] = [("H", i) for i in range(20)]
    g["aut_CZ"] = [("SDG", 4 * i) for i in range(5)] + [("SDG", 3 + 4 * i) for i in range(5)] + \
                  [("S", 1 + 4 * i) for i in range(5)] + [("S", 2 + 4 * i) for i in range(5)]
    g["S0S1"] = [("CZ", 0, 1), ("CZ", 4, 5), ("CZ", 8, 19), ("CZ", 9, 17), ("CZ", 10, 18),
                 ("CZ", 11, 16), ("CZ", 12, 14)] + [("S", q) for q in (2, 3, 6, 7, 13, 15)]
    return g


# ------------------------------------------------------------------ Sp(4,2) compiler
def _key(M):
    return M.astype(np.uint8).tobytes()


def cayley_costs(gens: dict, costs: dict, k=2):
    """Dijkstra over the group generated by the given symplectic matrices (right
    multiplication), from the identity. Returns dict key -> (cost, word)."""
    n = 2 * k
    I = np.eye(n, dtype=np.uint8)
    best = {_key(I): (0, [])}
    mats = {_key(I): I}
    heap = [(0, 0, _key(I))]
    cnt = 1
    while heap:
        c, _, kk = heapq.heappop(heap)
        if best[kk][0] < c:
            continue
        M = mats[kk]
        for name, G in gens.items():
            N = (M.astype(int) @ G.astype(int)) % 2
            nk = _key(N)
            nc = c + costs[name]
            if nk not in best or nc < best[nk][0]:
                best[nk] = (nc, best[kk][1] + [name])
                mats[nk] = N.astype(np.uint8)
                heapq.heappush(heap, (nc, cnt, nk))
                cnt += 1
    return best, mats


def cost_distribution(best):
    from collections import Counter
    return dict(sorted(Counter(c for c, _ in best.values()).items()))
